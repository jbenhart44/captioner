"""Shared WCAG alt-text (OOXML descr) writer for the captioner skill (v0.3).

Adds/maintains the `descr` attribute on each picture's <p:cNvPr> and PowerPoint's
native decorative marking. Shared by apply_captions.py (write path) and
verify.py (read-only coverage gate).

DESIGN FACTS (all empirically verified — Phase 0 spikes, run 2026-07-18_155600):

1. DETACHED-TREE HAZARD (spike 1): `iter_slide_pics()` returns `pic['el']` from a
   re-parsed detached copy of the spTree (`_oxml_pics.py:117-118`). Writing descr
   through it silently does NOT persist to the saved .pptx. Every write in this
   module therefore re-resolves the LIVE element via `slide.shapes._spTree`,
   using `iter_live_pic_cnvprs()` — the live-tree mirror of the enumerator's
   exact walk semantics (same depth-first order, mc:Choice-descendant pics
   skipped, hidden pics skipped), so index k in `iter_slide_pics(slide)` is the
   same logical picture as index k here. A pic_id cross-check guards the pairing
   (fail loudly, never write a guess).

2. DECORATIVE MARKING (spike 2): verified from 5,904 instances in real
   PowerPoint-authored corpus decks:
     <a:ext uri="{C183D7F6-B498-43B3-948B-1728B52AA6E4}">
       <adec:decorative xmlns:adec=
         "http://schemas.microsoft.com/office/drawing/2017/decorative" val="1"/>
     </a:ext>
   placed inside <a:extLst> as a CHILD of <p:cNvPr>. Corpus decorative shapes
   carry NO descr attribute — marking decorative here also clears descr.

3. PRESERVE-BY-DEFAULT (plan Q5, ratified): any non-empty pre-existing descr of
   unknown provenance is preserved. The ONLY exceptions:
     - it matches the captioner's own prior write (the descr-audit oracle) —
       then it is ours to update;
     - --replace-autogen-descr is passed AND the text matches the documented
       narrow autogen pattern list below.
   MS/tool-autogenerated patterns (documented, narrow, verified examples):
     a) suffix "Description automatically generated" (Office alt-text autogen);
     b) a bare image filename, e.g. "image.png" — python-pptx's add_picture
        default (verified in spike 1) and stock-photo filename metadata;
     c) prefix "A picture containing ..." (older Office autogen phrasing,
        cited by the 2026-05-17 descr-coverage audit).
"""
import csv
import os
import re
from lxml import etree

from _oxml_pics import NS, _walk, _ln

DECOR_EXT_URI = '{C183D7F6-B498-43B3-948B-1728B52AA6E4}'
ADEC_NS = 'http://schemas.microsoft.com/office/drawing/2017/decorative'
_A = NS['a']

# Sentinel write-value: "mark this picture decorative" (vs a descr string).
DECORATIVE_MARK = '__DECORATIVE_MARK__'

# Actions that mean "captioner wrote/owns this descr value" — used to build the
# oracle (hash -> last captioner-written value) from a prior descr-audit CSV.
_CAPTIONER_WROTE = {
    'descr-authored', 'descr-authored-forced', 'descr-updated',
    'descr-replaced-autogen', 'descr-unchanged',
}

_CATEGORY_PREFIX = re.compile(
    r'^\s*(photo|chart|diagram|screenshot|logo|map|illustration|image|graphic|'
    r'drawing|icon)\s*:\s*', re.IGNORECASE)

_AUTOGEN_SUFFIX = re.compile(r'description automatically generated\s*\.?\s*$',
                             re.IGNORECASE)
_AUTOGEN_FILENAME = re.compile(
    r'^[\w\-. ()]+\.(png|jpe?g|gif|bmp|tiff?|emf|wmf|svg|webp)\s*$',
    re.IGNORECASE)
_AUTOGEN_PREFIX = re.compile(
    r'^a (picture|screenshot|close-?up|group|drawing|diagram) containing\b',
    re.IGNORECASE)


def derive_alt_text(caption):
    """descr value derived from the visible caption: same string, category
    prefix stripped (a screen reader already announces "picture"/"graphic",
    so "Photo:" is redundant chatter). Deterministic — NOT a second source
    of truth. Falls back to the full caption if stripping empties it."""
    if not caption:
        return None
    stripped = _CATEGORY_PREFIX.sub('', caption).strip()
    return stripped if stripped else caption.strip()


def is_autogen_descr(text):
    """True iff `text` matches the documented narrow autogen pattern list
    (module docstring, fact 3). Deliberately conservative: anything not
    matching is treated as potentially human-authored and preserved."""
    t = (text or '').strip()
    if not t:
        return False
    return bool(_AUTOGEN_SUFFIX.search(t) or _AUTOGEN_FILENAME.match(t)
                or _AUTOGEN_PREFIX.match(t))


# --------------------------------------------------------------------------
# Live-element resolution (spike-1 consequence)
# --------------------------------------------------------------------------

def _has_choice_ancestor(el, stop):
    p = el.getparent()
    while p is not None and p is not stop:
        if _ln(p) == 'Choice':
            return True
        p = p.getparent()
    return False


def iter_live_pic_cnvprs(slide):
    """[(live_pic_el, live_cNvPr_or_None, pic_id), ...] in the SAME order as
    `iter_slide_pics(slide)` returns its dicts.

    Mirrors the enumerator exactly: same `_walk` depth-first traversal, pics
    under an <mc:Choice> excluded (the detached walk strips Choice first),
    hidden pics excluded. Elements returned are LIVE — writes persist on save.
    """
    spTree = slide.shapes._spTree
    raw = []
    _walk(spTree, 0, raw)
    out = []
    for pic_el, _depth in raw:
        if _has_choice_ancestor(pic_el, spTree.getparent()):
            continue
        cNvPr = pic_el.find('.//p:cNvPr', NS)
        if cNvPr is not None and cNvPr.get('hidden') == '1':
            continue
        pic_id = (cNvPr.get('id', '') or '') if cNvPr is not None else ''
        out.append((pic_el, cNvPr, pic_id))
    return out


# --------------------------------------------------------------------------
# descr / decorative primitives (operate on a cNvPr element)
# --------------------------------------------------------------------------

def get_descr(cNvPr):
    return (cNvPr.get('descr', '') or '') if cNvPr is not None else ''


def set_descr(cNvPr, text):
    cNvPr.set('descr', text)


def clear_descr(cNvPr):
    if cNvPr is not None and 'descr' in cNvPr.attrib:
        del cNvPr.attrib['descr']


def is_decorative_marked(cNvPr):
    """True iff cNvPr carries the verified PowerPoint decorative extension.
    Safe on BOTH live and detached elements (read-only)."""
    if cNvPr is None:
        return False
    for ext in cNvPr.findall('a:extLst/a:ext', NS):
        if ext.get('uri') == DECOR_EXT_URI:
            dec = ext.find('{%s}decorative' % ADEC_NS)
            if dec is not None and dec.get('val') in ('1', 'true'):
                return True
    return False


def mark_decorative(cNvPr):
    """Idempotently add the verified decorative extension; clears descr
    (corpus decorative shapes carry no descr — module docstring, fact 2)."""
    clear_descr(cNvPr)
    if is_decorative_marked(cNvPr):
        return
    extLst = cNvPr.find('a:extLst', NS)
    if extLst is None:
        # a:extLst is the LAST child in the cNvPr content model — append is valid.
        extLst = etree.SubElement(cNvPr, '{%s}extLst' % _A)
    ext = None
    for e in extLst.findall('a:ext', NS):
        if e.get('uri') == DECOR_EXT_URI:
            ext = e
            break
    if ext is None:
        ext = etree.SubElement(extLst, '{%s}ext' % _A)
        ext.set('uri', DECOR_EXT_URI)
    dec = ext.find('{%s}decorative' % ADEC_NS)
    if dec is None:
        dec = etree.SubElement(ext, '{%s}decorative' % ADEC_NS,
                               nsmap={'adec': ADEC_NS})
    dec.set('val', '1')


# --------------------------------------------------------------------------
# Decision table (pure — unit-testable without any .pptx)
# --------------------------------------------------------------------------

def decide_descr(current, oracle_val, decorative, alt_text, already_marked,
                 replace_autogen=False, force_overwrite_edits=False):
    """Resolve what to do with one picture's descr.

    Inputs:
      current       existing descr on the LIVE element ('' if none)
      oracle_val    what captioner last wrote for this image hash (None = never)
      decorative    True if the decorative signals fire ([decorative] vision
                    caption or repeated-background hash)
      alt_text      derived descr text to write (None if no caption available)
      already_marked  True if the decorative extension is already present
      replace_autogen  --replace-autogen-descr flag
      force_overwrite_edits  --force-overwrite-edits flag

    Returns (action, write_value):
      write_value is a str to set as descr, DECORATIVE_MARK to mark decorative,
      or None for no change. Preserve-by-default per plan Q5 (ratified).
    """
    cur = (current or '').strip()
    ours = oracle_val is not None and cur == oracle_val.strip()

    if not cur:
        if decorative:
            if already_marked:
                return 'descr-decorative-unchanged', None
            return 'descr-decorative-marked', DECORATIVE_MARK
        if alt_text:
            return 'descr-authored', alt_text
        return 'descr-skipped-no-caption', None

    # Non-empty current descr.
    if oracle_val is not None and not ours:
        # Value changed since captioner wrote it -> human hand-edit.
        if force_overwrite_edits:
            if decorative:
                return 'descr-decorative-marked-forced', DECORATIVE_MARK
            if alt_text:
                return 'descr-authored-forced', alt_text
        return 'descr-preserved-hand-edit', None
    if ours:
        if decorative:
            return 'descr-decorative-marked', DECORATIVE_MARK
        if alt_text is None or alt_text == cur:
            return 'descr-unchanged', None
        return 'descr-updated', alt_text
    # Pre-existing descr of unknown provenance (no oracle entry).
    if replace_autogen and is_autogen_descr(cur):
        if decorative:
            return 'descr-decorative-replaced-autogen', DECORATIVE_MARK
        if alt_text:
            return 'descr-replaced-autogen', alt_text
    return 'descr-preserved-pre-existing', None


def apply_decision(cNvPr, write_value):
    """Apply a decide_descr() write_value to a LIVE cNvPr element."""
    if write_value is None:
        return
    if write_value == DECORATIVE_MARK:
        mark_decorative(cNvPr)
    else:
        set_descr(cNvPr, write_value)


# --------------------------------------------------------------------------
# Oracle (descr-audit CSV): hash -> last captioner-written descr value
# --------------------------------------------------------------------------

DESCR_AUDIT_FIELDS = ['slide', 'pic_id', 'image_hash', 'prior_descr',
                      'new_descr', 'action', 'run_timestamp']


def descr_audit_path(audit_dir, deck, dry_run=False):
    suffix = '_descr_audit_dryrun.csv' if dry_run else '_descr_audit.csv'
    return os.path.join(audit_dir, f'{deck}{suffix}')


def load_descr_oracle(audit_dir, deck):
    """hash -> descr value captioner last wrote (from prior descr-audit CSV).
    Only rows whose action means "captioner wrote this" feed the oracle; a
    decorative mark contributes no descr value. Missing file -> empty oracle
    (every pre-existing descr then reads as unknown provenance -> preserved)."""
    oracle = {}
    p = descr_audit_path(audit_dir, deck)
    if not os.path.exists(p):
        return oracle
    try:
        with open(p, encoding='utf-8', newline='') as f:
            for r in csv.DictReader(f):
                h = r.get('image_hash', '')
                act = r.get('action', '')
                val = r.get('new_descr', '')
                if not h:
                    continue
                if act in _CAPTIONER_WROTE and val:
                    oracle[h] = val
                elif act == 'descr-unchanged' and not val:
                    # unchanged rows may carry the standing value in prior_descr
                    pv = r.get('prior_descr', '')
                    if pv:
                        oracle[h] = pv
    except Exception:
        pass
    return oracle


def write_descr_audit(audit_dir, deck, rows, dry_run=False):
    if not rows:
        return None
    p = descr_audit_path(audit_dir, deck, dry_run=dry_run)
    with open(p, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=DESCR_AUDIT_FIELDS, extrasaction='ignore')
        w.writeheader()
        for r in rows:
            w.writerow(r)
    return p
